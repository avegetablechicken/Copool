#!/usr/bin/env python3
"""Reuse Swift's localization strings in the Rust desktop UI (no translated forks)."""
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
locales = {}
for source in sorted((root / 'Sources/Copool/Resources').glob('*.lproj/Localizable.strings')):
    pairs = re.findall(r'"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', source.read_text())
    locales[source.parent.stem] = {json.loads('"'+k+'"'): json.loads('"'+v+'"') for k, v in pairs}
(root / 'desktop/ui/locales.js').write_text('// Generated by scripts/sync_rust_locales.py from Swift resources.\nwindow.COPOOL_LOCALES = '+json.dumps(locales, ensure_ascii=False, separators=(',', ':'))+';\n')
